








# Evaluating Bollean expressions
print(10 > 9) # Is 10 greater than 9?

print(10 < 9) # Is 10 less than 9?

# Comparision Operators
# Allows Python to compare two values

#  ==(Equal to)
favorite_color = "pink"

print(favorite_color == "blue")
print(favorite_color == "pink")

#  !=(Not Equal to)
password = "abc123"

print(password == "python123")

#  > Greater than
balance = 500
purchase = 200

print(balance > purchase)

#  < Less than
temperature = 65
print(temperature < 32)

# >= Greater than or equal to
age = 18
print(age >= 18)

#  <= less than or equal to
items = 10
maximum_items = 10
print(items <= maximum_items)

# SINGLE EQUAL SIGN (=) IS AN ASSIGMENT OPERATOR

# DOUBLE EQUAL SIGN (==) IS A CPARISON OPERATOR